"""Generate comprehensive pruning + quantization plots for the book chapter.

Reads from pruning_results/comprehensive_*.csv files generated by
generate_comprehensive_analysis.py.

Plots:
1. Pruning method comparison: 2×2 grid (Swin-T, DeiT3-S, Swin-B, DeiT3-B)
   - Horizontal bars showing FP32 rank-1 for each pruning method
   - Baseline dashed line, size annotations

2. INT8 quantization impact: bar chart showing FP32→INT8 rank-1 drop per model

3. Pareto front: 2×2 grid per architecture (size vs accuracy)
"""

import pandas as pd
import matplotlib.pyplot as plt
import matplotlib.patches as mpatches
import matplotlib.lines as mlines
import numpy as np
import os

OUT_DIR = os.path.dirname(os.path.abspath(__file__))
IMG_DIR = os.path.join(os.path.dirname(OUT_DIR),
                       "docs", "scalable_vits_for_embedded_systems", "figures")
os.makedirs(IMG_DIR, exist_ok=True)


def save(fig, name):
    """Save to both pruning_results/ and docs figures/."""
    fig.savefig(os.path.join(OUT_DIR, name), dpi=150, bbox_inches="tight")
    fig.savefig(os.path.join(IMG_DIR, name.replace(".png", ".pdf")),
                bbox_inches="tight")
    fig.savefig(os.path.join(IMG_DIR, name), dpi=150, bbox_inches="tight")
    plt.close(fig)
    print(f"  Saved {name}")


# ── Styling ──────────────────────────────────────────────────────────────────

plt.rcParams.update({
    "font.size": 18,
    "axes.titlesize": 20,
    "axes.labelsize": 18,
    "xtick.labelsize": 16,
    "ytick.labelsize": 16,
    "legend.fontsize": 16,
    "figure.dpi": 150,
    "savefig.bbox": "tight",
    "savefig.pad_inches": 0.15,
    "font.family": "serif",
})

# Colors by pruning method
METHOD_COLORS = {
    "Original":       "#888888",
    "Heads 10%":      "#4a90d9",
    "Heads 25%":      "#2ca02c",
    "Heads 50%":      "#ff7f0e",
    "Blocks":         "#d62728",
}

# Markers by precision
PREC_MARKERS = {"FP32": "o", "FP16": "s", "INT8": "^"}


def classify_method(method_str, prune_method):
    """Return display method key."""
    if prune_method == "None":
        return "Original"
    if "50%" in prune_method:
        return "Heads 50%"
    if "25%" in prune_method:
        return "Heads 25%"
    if "10%" in prune_method:
        return "Heads 10%"
    if "block" in prune_method.lower():
        return "Blocks"
    return "Original"


# ── Load data ────────────────────────────────────────────────────────────────

comp = pd.read_csv(os.path.join(OUT_DIR, "comprehensive_compression.csv"), keep_default_na=False)
full = pd.read_csv(os.path.join(OUT_DIR, "comprehensive_full_metrics.csv"), keep_default_na=False)


# ═══════════════════════════════════════════════════════════════════════════════
# Plot 1: Pruning method comparison — 2×2 grid, all 4 architectures
# ═══════════════════════════════════════════════════════════════════════════════
print("Generating pruning method comparison (2×2)...")

# Panel definitions: (architecture, variant_for_pruning, display_title, baseline_rank1, bar_color_base)
PANELS = [
    ("Swin-T", "Baseline", "Swin-T (Baseline)", 0.534, "#1f77b4"),
    ("DeiT3-S", "Baseline", "DeiT3-S (Baseline)", 0.552, "#ff7f0e"),
    ("Swin-B", "Baseline", "Swin-B (Baseline)", 0.526, "#2ca02c"),
    ("DeiT3-B", "LoRA", "DeiT3-B (Baseline)", 0.583, "#d62728"),
]

fig, axes = plt.subplots(2, 2, figsize=(12, 8))
axes_flat = axes.flatten()

for idx, (arch, variant, title, baseline_rank1, base_color) in enumerate(PANELS):
    ax = axes_flat[idx]

    # Get FP32 rows for this arch+variant (baseline + pruned)
    mask = (comp["architecture"] == arch) & (comp["precision"] == "FP32")
    # For pruned rows, match variant and exclude "None" prune method
    pruned_mask = mask & (comp["variant"] == variant) & (comp["prune_method"] != "None")
    baseline_mask = mask & (comp["variant"] == variant) & (comp["prune_method"] == "None")

    baseline_row = comp[baseline_mask]
    pruned_rows = comp[pruned_mask].copy()
    pruned_rows = pruned_rows[pruned_rows["prune_method"].notna()]

    # Fixed display order (top to bottom): Original, Blocks, 10% heads, 25% heads, 50% heads
    # barh draws bottom-to-top, so reverse the order in the list
    METHOD_ORDER = ["50% heads", "25% heads", "10% heads", "blocks", "Original"]

    def _sort_key(pm_str):
        pm_lower = pm_str.lower()
        for i, pat in enumerate(METHOD_ORDER):
            if pat.lower() in pm_lower:
                return i
        return len(METHOD_ORDER)

    import matplotlib.colors as mcolors

    # Build bar data in fixed order
    labels = []
    values = []
    sizes = []
    colors = []

    # Collect pruned entries keyed by sort position
    entries = []
    for _, row in pruned_rows.iterrows():
        pm = row["prune_method"]
        # Skip 50% heads (only present for DeiT3-B)
        if "50%" in pm:
            continue
        entries.append((pm, float(row["rank_at_1"]), float(row["size_MB"])))
    entries.sort(key=lambda e: _sort_key(e[0]))

    # Add baseline first (will appear at top after reversal by barh)
    if len(baseline_row) > 0:
        br = baseline_row.iloc[0]
        rgb = mcolors.to_rgb(base_color)
        light_color = tuple(min(1.0, c + 0.4) for c in rgb)
        entries.insert(0, ("Original", float(br["rank_at_1"]), float(br["size_MB"])))

    # Reverse so barh renders top item at top of y-axis
    entries = entries[::-1]

    for pm, val, sz in entries:
        if pm == "Original":
            labels.append("Original")
            rgb = mcolors.to_rgb(base_color)
            colors.append(tuple(min(1.0, c + 0.4) for c in rgb))
        else:
            labels.append(f"Pruned\n{pm}")
            colors.append(base_color)
        values.append(val)
        sizes.append(sz)

    y = np.arange(len(labels))
    bars = ax.barh(y, values, color=colors, edgecolor="white", height=0.6)

    for bar, val, sz in zip(bars, values, sizes):
        ax.text(bar.get_width() + 0.002, bar.get_y() + bar.get_height() / 2,
                f"{sz:.0f} MB", va="center", fontsize=14)

    ax.set_yticks(y)
    ax.set_yticklabels(labels, fontsize=14)
    ax.set_xlabel("Rank-1 Identification Rate")
    ax.set_title(title, fontweight="bold")
    ax.axvline(x=baseline_rank1, color="red", ls="--", alpha=0.5, lw=1.2)

    # Set x-axis range based on data
    min_val = min(values) if values else 0.4
    max_val = max(values) if values else 0.6
    margin = (max_val - min_val) * 0.3
    ax.set_xlim(min_val - margin, max_val + margin + 0.03)
    ax.grid(axis="x", alpha=0.3)

fig.suptitle("Pruning Method Comparison (FP32)", fontsize=22)
fig.tight_layout()
save(fig, "pruning_method_comparison.png")


# ═══════════════════════════════════════════════════════════════════════════════
# Plot 2: INT8 impact on pruned models
# ═══════════════════════════════════════════════════════════════════════════════
print("Generating INT8 impact plot...")

fp32_rows = full[full["precision"] == "FP32"][["model", "rank@1", "architecture", "variant", "prune_method"]].copy()
int8_rows = full[full["precision"] == "INT8"][["model", "rank@1"]].copy()

merged = fp32_rows.merge(int8_rows, on="model", suffixes=("_fp32", "_int8"))
merged["drop_pp"] = (merged["rank@1_fp32"].astype(float) - merged["rank@1_int8"].astype(float)) * 100

# Sort by architecture then drop
merged = merged.sort_values(["architecture", "drop_pp"], ascending=[True, False])

# Color by architecture
ARCH_COLORS = {
    "Swin-T": "#1f77b4",
    "DeiT3-S": "#ff7f0e",
    "Swin-B": "#2ca02c",
    "DeiT3-B": "#d62728",
}

bar_colors = [ARCH_COLORS.get(a, "#888") for a in merged["architecture"]]

# Build labels
def _make_label(row):
    parts = [row["architecture"]]
    if row["variant"] not in ("Baseline",):
        vshort = row["variant"].replace("KD Best (α=0.1)", "KD").replace("KD Best (α=0.0)", "KD").replace("KD CVLFace (α=0.7)", "KD").replace("LoRA", "LoRA")
        parts.append(vshort)
    parts.append(row["prune_method"])
    return "\n".join(parts)

labels = [_make_label(row) for _, row in merged.iterrows()]

fig, ax = plt.subplots(figsize=(14, 5))
x = np.arange(len(merged))
bars = ax.bar(x, merged["drop_pp"], color=bar_colors, edgecolor="white", width=0.65)

for bar, val in zip(bars, merged["drop_pp"]):
    ypos = max(val, 0) + 0.02
    ax.text(bar.get_x() + bar.get_width() / 2, ypos,
            f"{val:.2f}", ha="center", va="bottom", fontsize=8)

ax.set_xticks(x)
ax.set_xticklabels(labels, rotation=45, ha="right", fontsize=8)
ax.set_ylabel("Rank-1 Accuracy Drop (pp)")
ax.set_title("INT8 Quantization Impact on Pruned Models")
ax.grid(axis="y", alpha=0.3)
ax.axhline(y=0, color="black", lw=0.8)

# Legend by architecture
handles = [mpatches.Patch(color=c, label=a) for a, c in ARCH_COLORS.items()]
ax.legend(handles=handles, loc="upper right", fontsize=10)

ymax = merged["drop_pp"].max()
ymin = merged["drop_pp"].min()
ax.set_ylim(min(ymin - 0.2, -0.2), max(ymax * 1.4, 0.6))

fig.tight_layout()
save(fig, "int8_impact_pruned.png")


# ═══════════════════════════════════════════════════════════════════════════════
# Plot 3: Pareto front — 2×2 grid by architecture
# ═══════════════════════════════════════════════════════════════════════════════
print("Generating Pareto plots...")

pareto = pd.read_csv(os.path.join(OUT_DIR, "comprehensive_pareto.csv"), keep_default_na=False)

PARETO_PANELS = [
    ("Swin-T", "Swin-T"),
    ("DeiT3-S", "DeiT3-S"),
    ("Swin-B", "Swin-B"),
    ("DeiT3-B", "DeiT3-B"),
]


def make_pareto(x_col, x_label, title, filename):
    fig, axes = plt.subplots(2, 2, figsize=(12, 9))
    axes_flat = axes.flatten()

    for idx, (arch, display_name) in enumerate(PARETO_PANELS):
        ax = axes_flat[idx]

        arch_rows = pareto[pareto["architecture"] == arch]

        for _, row in arch_rows.iterrows():
            mkey = classify_method(row["method"], "None" if "Original" in row["method"] else row["method"].replace("Pruned ", ""))
            # Determine precision from method string
            if "INT8" in str(row["method"]):
                prec = "INT8"
            elif "FP16" in str(row["method"]):
                prec = "FP16"
            else:
                prec = "FP32"

            color = METHOD_COLORS.get(mkey, "#888")
            marker = PREC_MARKERS.get(prec, "o")

            ax.scatter(
                row[x_col], row["rank_at_1"],
                c=color, marker=marker, s=80, alpha=0.85, zorder=3,
                edgecolors="black", linewidths=0.6,
            )

        ax.set_xlabel(x_label, fontsize=10)
        ax.set_ylabel("Rank-1", fontsize=10)
        ax.set_title(display_name, fontsize=12, fontweight="bold")
        ax.grid(True, alpha=0.25)
        ax.tick_params(labelsize=9)

    # Shared legend
    method_handles = [mpatches.Patch(color=c, label=k) for k, c in METHOD_COLORS.items()
                      if k != "Heads 50%"]  # Only show methods that appear
    prec_handles = [mlines.Line2D([], [], marker=PREC_MARKERS[p], color="gray",
                                  linestyle="None", markersize=7, label=p)
                    for p in ["FP32", "FP16", "INT8"]]
    all_handles = method_handles + prec_handles

    fig.legend(handles=all_handles, loc="upper center",
               bbox_to_anchor=(0.5, 1.01), ncol=7,
               framealpha=0.95, fontsize=9, handletextpad=0.4,
               columnspacing=1.0)

    fig.suptitle(title, fontsize=14, y=1.05)
    fig.tight_layout(rect=[0, 0, 1, 0.97])
    save(fig, filename)


make_pareto("size_MB", "Model Size (MB)",
            "Accuracy vs. Model Size — Pruned + Quantized",
            "pareto_size_vs_accuracy.png")

make_pareto("compression_ratio", "Compression Ratio (×)",
            "Accuracy vs. Compression Ratio — Pruned + Quantized",
            "pareto_compression_vs_accuracy.png")


print("\nAll plots generated successfully.")
